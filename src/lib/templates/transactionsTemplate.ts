export function generateTransactionsTemplate(companyId?: string): string {
  const headers = [
    'entry_external_id',
    'date',
    'description',
    'account_code',
    'dc',
    'amount',
    'reference',
    'memo',
    'payment_method',
    'attachment_url',
    'period_code',
    'line_no'
  ].join(',');

  let examples: string[] = [];

  switch (companyId) {
    case 'al-taqaddum':
      examples = generateAlTaqaddumExamples();
      break;
    case 'al-fajr':
      examples = generateAlFajrExamples();
      break;
    case 'al-raida-trading':
      examples = generateAlRaidaTradingExamples();
      break;
    case 'al-sinaaat-advanced':
      examples = generateAlSinaaatAdvancedExamples();
      break;
    default:
      examples = generateGeneralExamples();
  }

  return [headers, ...examples].join('\n');
}


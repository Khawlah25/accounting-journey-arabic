export function getTemplateFilename(companyId?: string): string {
  const companyNames: Record<string, string> = {
    'al-taqaddum': 'التقدم_التقنية',
    'al-fajr': 'الفجر_العقارية', 
    'al-raida-trading': 'الرائدة_للتجارة',
    'al-sinaaat-advanced': 'الصناعات_المتقدمة'
  };
  
  const companyName = companyId ? companyNames[companyId] || 'عامة' : 'عامة';
  return `transactions_template_${companyName}.csv`;
}

